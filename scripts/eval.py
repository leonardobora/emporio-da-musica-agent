#!/usr/bin/env python3
"""Live evaluation: run the scenario suite against one or more real models (ADR 0007).

    python scripts/eval.py                       # models from MODELS, transcripts not written
    python scripts/eval.py --models deepseek-chat,deepseek-flash --report docs/notes/03-model-bakeoff.md
    python scripts/eval.py --transcripts         # also refreshes examples/*.md for the first model

Needs a valid DEEPSEEK_API_KEY (or set DEEPSEEK_BASE_URL to another OpenAI-compatible endpoint).
"""

from __future__ import annotations

import argparse
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from emporio import database, runner  # noqa: E402
from emporio.config import Config  # noqa: E402
from emporio.llm import DeepSeekClient, LLMError  # noqa: E402

PRICE_PER_M_INPUT = 0.28  # USD per 1M input tokens  (deepseek-chat list price)
PRICE_PER_M_OUTPUT = 0.42  # USD per 1M output tokens
PRICE_PER_M_CACHE_HIT = 0.028


def estimate_cost(usage: dict[str, int]) -> float:
    cache_hits = usage.get("prompt_cache_hit_tokens", 0)
    prompt = usage.get("prompt_tokens", 0)
    missed = usage.get("prompt_cache_miss_tokens", max(prompt - cache_hits, 0))
    completion = usage.get("completion_tokens", 0)
    return (
        missed / 1_000_000 * PRICE_PER_M_INPUT
        + cache_hits / 1_000_000 * PRICE_PER_M_CACHE_HIT
        + completion / 1_000_000 * PRICE_PER_M_OUTPUT
    )


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--models", default="deepseek-chat,deepseek-flash")
    parser.add_argument("--report", type=Path)
    parser.add_argument("--transcripts", action="store_true")
    parser.add_argument("--scenario-dir", type=Path, default=ROOT / "examples" / "scenarios")
    parser.add_argument("--temperature", type=float, default=0.0, help="eval runs at 0 for reproducibility")
    args = parser.parse_args()

    cfg = Config.from_env()
    models = [m.strip() for m in args.models.split(",") if m.strip()]
    scenarios = sorted(args.scenario_dir.glob("*.json"))
    conn = database.connect(cfg.db_path)
    database.load_store(conn, cfg.data_dir)

    report_lines = [
        "# Model bake-off",
        "",
        f"Generated by `scripts/eval.py` on {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')}.",
        f"Provider: `{cfg.base_url}` · scenarios: {len(scenarios)} · same prompts, same tools, same data.",
        "",
        "| model | scenario | result | failed checks | prompt tokens | completion | est. cost (USD) |",
        "|---|---|---|---|---|---|---|",
    ]

    overall_failures = 0
    for index, model in enumerate(models):
        client = DeepSeekClient(
            api_key=cfg.api_key, base_url=cfg.base_url, model=model, temperature=args.temperature
        )
        print(f"\n=== {model} ===")
        for path in scenarios:
            try:
                result = runner.run_scenario(
                    path,
                    client,
                    conn,
                    ROOT / "examples",
                    write_transcript=args.transcripts and index == 0,
                )
            except LLMError as exc:
                print(f"  ERRO {path.name}: {exc}")
                report_lines.append(f"| `{model}` | {path.name} | erro | {exc} | 0 | 0 | 0.0000 |")
                overall_failures += 1
                continue
            failed = [check.name for check in result.checks if not check.passed]
            overall_failures += len(failed)
            cost = estimate_cost(result.usage)
            mark = "PASSOU" if result.passed else "FALHOU"
            print(f"  {mark} {result.scenario_id} ({len(result.checks) - len(failed)}/{len(result.checks)}) ${cost:.4f}")
            for name in failed:
                print(f"      ✗ {name}")
            if failed:
                for index, answer in enumerate(result.answers, start=1):
                    print(f"      ↳ turno {index}: {' '.join(answer.split())[:400]}")
            report_lines.append(
                f"| `{model}` | {result.scenario_id} | {mark} | {', '.join(failed) or '—'} | "
                f"{result.usage.get('prompt_tokens', 0):,} | {result.usage.get('completion_tokens', 0):,} | "
                f"{cost:.4f} |"
            )

    summary = ["", "## Summary", "", "| model | scenarios passed | failed checks | est. cost (USD) |", "|---|---|---|---|"]
    for model in models:
        rows = [r for r in report_lines if r.startswith(f"| `{model}` |")]
        passed = sum(1 for r in rows if "| PASSOU |" in r)
        failed_checks = sum(len([c for c in r.split("|")[4].split(",") if c.strip() and c.strip() != "—"]) for r in rows)
        cost = sum(float(r.split("|")[7].strip()) for r in rows if r.split("|")[7].strip().replace(".", "").isdigit())
        summary.append(f"| `{model}` | {passed}/{len(scenarios)} | {failed_checks} | {cost:.4f} |")
    report_lines.extend(summary)

    if args.report:
        args.report = args.report if args.report.is_absolute() else (ROOT / args.report)
        args.report.parent.mkdir(parents=True, exist_ok=True)
        args.report.write_text("\n".join(report_lines) + "\n", encoding="utf-8")
        print(f"\nrelatório: {args.report.relative_to(ROOT)}")
    return 1 if overall_failures else 0


if __name__ == "__main__":
    raise SystemExit(main())
