"""Scripted runs: feed a scenario file to the agent and write the transcript to examples/."""

from __future__ import annotations

import json
import re
import sqlite3
from dataclasses import dataclass, field
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from . import database
from .agent import Agent, AgentReply
from .llm import DeepSeekClient

MAX_TOOL_JSON = 700


@dataclass
class ScenarioCheck:
    name: str
    passed: bool
    detail: str = ""


@dataclass
class ScenarioResult:
    scenario_id: str
    title: str
    passed: bool
    checks: list[ScenarioCheck] = field(default_factory=list)
    transcript_path: Path | None = None
    usage: dict[str, Any] = field(default_factory=dict)


def load_scenario(path: Path) -> dict[str, Any]:
    return json.loads(Path(path).read_text(encoding="utf-8"))


def _trim(result: dict[str, Any]) -> str:
    text = json.dumps(result, ensure_ascii=False, default=str, indent=2)
    if len(text) > MAX_TOOL_JSON:
        text = text[:MAX_TOOL_JSON].rstrip() + "\n  … (truncado)"
    return text


def _check(name: str, ok: bool, detail: str = "") -> ScenarioCheck:
    return ScenarioCheck(name=name, passed=ok, detail=detail)


def evaluate(scenario: dict[str, Any], replies: list[AgentReply]) -> list[ScenarioCheck]:
    """Assertions declared by the scenario file; used by the live eval, ignored by the transcript."""
    expect = scenario.get("expect") or {}
    checks: list[ScenarioCheck] = []
    used = [step.tool for reply in replies for step in reply.steps]
    answers = "\n".join(reply.text for reply in replies)

    required = expect.get("tools_required") or []
    if required:
        missing = [tool for tool in required if tool not in used]
        checks.append(_check(f"ferramentas obrigatórias {required}", not missing, f"faltaram: {missing}"))

    forbidden = expect.get("tools_forbidden") or []
    if forbidden:
        seen = [tool for tool in forbidden if tool in used]
        checks.append(_check(f"ferramentas proibidas {forbidden}", not seen, f"usadas: {seen}"))

    for needle in expect.get("reply_contains") or []:
        checks.append(_check(f'resposta contém "{needle}"', needle.lower() in answers.lower()))

    for needle in expect.get("reply_not_contains") or []:
        checks.append(_check(f'resposta NÃO contém "{needle}"', needle.lower() not in answers.lower()))

    for pattern in expect.get("reply_matches") or []:
        checks.append(_check(f"resposta casa /{pattern}/", bool(re.search(pattern, answers, re.I))))

    for spec in scenario.get("turn_expect") or []:
        index = int(spec.get("index", 0)) - 1
        label = f"turno {index + 1}"
        if not 0 <= index < len(replies):
            checks.append(_check(f"{label} existe", False, "cenário tem menos turnos que o esperado"))
            continue
        text = replies[index].text
        tools_used = [step.tool for step in replies[index].steps]
        for needle in spec.get("reply_contains") or []:
            checks.append(_check(f'{label} contém "{needle}"', needle.lower() in text.lower()))
        for needle in spec.get("reply_not_contains") or []:
            checks.append(_check(f'{label} NÃO contém "{needle}"', needle.lower() not in text.lower()))
        for pattern in spec.get("reply_matches") or []:
            checks.append(_check(f"{label} casa /{pattern}/", bool(re.search(pattern, text, re.I))))
        for tool in spec.get("tools_required") or []:
            checks.append(_check(f"{label} usou {tool}", tool in tools_used))

    return checks


def render_transcript(
    scenario: dict[str, Any],
    session_id: str,
    model: str,
    turns: list[tuple[str, AgentReply]],
    checks: list[ScenarioCheck],
) -> str:
    stamp = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    total_usage: dict[str, int] = {}
    for _, reply in turns:
        for key, value in reply.usage.items():
            if isinstance(value, int):
                total_usage[key] = total_usage.get(key, 0) + value
    usage_line = ", ".join(f"{k}={v:,}".replace(",", ".") for k, v in sorted(total_usage.items())) or "n/d"

    lines = [
        f"<!-- Generated by `python -m emporio run-scenario examples/scenarios/{scenario['id']}.json`"
        " — a real run, do not edit. -->",
        f"# {scenario['id']} — {scenario['title']}",
        "",
        f"**Objetivo:** {scenario.get('goal', '—')}",
        "",
        f"**Modelo:** `{model}` · **Sessão:** `{session_id}` · **Executado em:** {stamp}",
        f"**Tokens:** {usage_line}",
        "",
        "---",
        "",
    ]

    for customer_text, reply in turns:
        lines.append(f"**Cliente:** {customer_text}")
        lines.append("")
        for step in reply.steps:
            args = json.dumps(step.arguments, ensure_ascii=False)
            lines.append(f"`{step.tool}({args})`")
            lines.append("")
            lines.append("```json")
            lines.append(_trim(step.result))
            lines.append("```")
            lines.append("")
        answer = reply.text.replace("\n", "  \n") if reply.text else "_(sem resposta)_"
        lines.append(f"**Agente:** {answer}")
        lines.append("")
        lines.append("---")
        lines.append("")

    if checks:
        lines.append("## Checagens automáticas desta execução")
        lines.append("")
        for check in checks:
            mark = "✅" if check.passed else "❌"
            detail = f" — {check.detail}" if check.detail else ""
            lines.append(f"- {mark} {check.name}{detail}")
        lines.append("")

    return "\n".join(lines)


def run_scenario(
    scenario_path: Path,
    client: DeepSeekClient,
    conn: sqlite3.Connection,
    out_dir: Path,
    write_transcript: bool = True,
) -> ScenarioResult:
    scenario = load_scenario(scenario_path)
    session_id = database.start_session(conn, client.model, channel="scenario")
    agent = Agent(client, conn, session_id)
    turns: list[tuple[str, AgentReply]] = []
    for customer_text in scenario["turns"]:
        turns.append((customer_text, agent.reply(customer_text)))

    checks = evaluate(scenario, [reply for _, reply in turns])
    usage: dict[str, int] = {}
    for _, reply in turns:
        for key, value in reply.usage.items():
            if isinstance(value, int):
                usage[key] = usage.get(key, 0) + value

    transcript_path = None
    if write_transcript:
        out_dir.mkdir(parents=True, exist_ok=True)
        transcript_path = out_dir / f"{scenario['id']}.md"
        transcript_path.write_text(
            render_transcript(scenario, session_id, client.model, turns, checks), encoding="utf-8"
        )

    return ScenarioResult(
        scenario_id=scenario["id"],
        title=scenario["title"],
        passed=all(check.passed for check in checks) if checks else True,
        checks=checks,
        transcript_path=transcript_path,
        usage=usage,
    )
